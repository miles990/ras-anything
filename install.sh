#!/bin/sh
# install.sh — install the ras-anything CLI and agent skills for this user.
# Idempotent: safe to re-run. Companion: `make install` / `make uninstall`.
#
#   ./install.sh              # install or refresh
#   ./install.sh --uninstall  # remove the CLI shim/venv and skill copies this script installed
#
# The CLI is installed with pipx when it is on PATH; otherwise a venv is created at
# ~/.local/share/ras-anything and a shim is written to ~/.local/bin/ras-anything.
# Skills are copied to ~/.claude/skills/ras-anything and ~/.codex/skills/ras-anything.
# This script never makes the repo public and never publishes to PyPI or npm.

set -eu

usage() {
  cat <<'USAGE'
Usage: ./install.sh [--force] [--uninstall]

  (no args)       Install or refresh the ras-anything CLI and agent skills.
                  Idempotent: re-running upgrades the same layout in place.
  --force         Overwrite an existing skill or ~/.local/bin/ras-anything not created by this installer.
  --uninstall     Remove the CLI (pipx package or venv+shim) and the skill
                  copies this script installed. Other skills are left alone.
  -h, --help      Show this help.

Layout:
  CLI (pipx)   pipx-managed ras-anything on ~/.local/bin
  CLI (venv)   ~/.local/share/ras-anything  +  ~/.local/bin/ras-anything
  Skills       ~/.claude/skills/ras-anything/SKILL.md
               ~/.codex/skills/ras-anything/SKILL.md
USAGE
}

die() { printf 'install.sh: %s\n' "$*" >&2; exit 1; }

ROOT=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
HOME=${HOME:-}
[ -n "$HOME" ] || die "HOME is not set"

DATA_DIR=$HOME/.local/share/ras-anything
BIN_DIR=$HOME/.local/bin
VENV_DIR=$DATA_DIR/venv
SHIM=$BIN_DIR/ras-anything
MARKER=$DATA_DIR/installed-by-install-sh
SHIM_MARK="# ras-anything shim — generated by install.sh"
SKILL_MARK=".installed-by-ras-anything"
SKILL_SRC=$ROOT/skills/ras-anything
CLAUDE_SKILL=$HOME/.claude/skills/ras-anything
CODEX_SKILL=$HOME/.codex/skills/ras-anything

have() { command -v "$1" >/dev/null 2>&1; }

python_bin() {
  if have python3; then
    command -v python3
  elif have python; then
    command -v python
  else
    die "Python 3.10+ is required but python3 was not found on PATH"
  fi
}

check_python() {
  py=$(python_bin)
  ver=$("$py" -c 'import sys; print("%d.%d" % sys.version_info[:2])')
  major=${ver%%.*}
  minor=${ver#*.}
  if [ "$major" -lt 3 ] || { [ "$major" -eq 3 ] && [ "$minor" -lt 10 ]; }; then
    die "Python 3.10+ is required (found $ver at $py)"
  fi
  printf '%s\n' "$py"
}

FORCE=0

is_our_shim() {
  [ ! -L "$1" ] && [ -f "$1" ] && grep -q "$SHIM_MARK" "$1"
}

skill_is_ours() {
  [ -f "$1/$SKILL_MARK" ]
}

copy_skill() {
  src=$1
  dest=$2
  [ -f "$src/SKILL.md" ] || die "skill source missing: $src/SKILL.md"
  if [ -e "$dest/SKILL.md" ] || [ -L "$dest/SKILL.md" ]; then
    if ! skill_is_ours "$dest" && [ "$FORCE" -ne 1 ]; then
      if ! cmp -s "$src/SKILL.md" "$dest/SKILL.md" 2>/dev/null; then
        die "refusing to overwrite existing skill at $dest/SKILL.md (not installed by ras-anything; remove it or re-run with --force)"
      fi
    fi
  fi
  mkdir -p "$dest"
  # Refresh contents without deleting unexpected user files in the dest dir.
  cp -f "$src/SKILL.md" "$dest/SKILL.md"
  for f in "$src"/*; do
    [ -f "$f" ] || continue
    base=$(basename "$f")
    [ "$base" = "SKILL.md" ] && continue
    cp -f "$f" "$dest/$base"
  done
  printf '%s\n' "installed-by: ras-anything/install.sh" > "$dest/$SKILL_MARK"
}

remove_skill() {
  dest=$1
  if [ -d "$dest" ] && skill_is_ours "$dest"; then
    rm -f "$dest/SKILL.md" "$dest/$SKILL_MARK"
    rmdir "$dest" 2>/dev/null || true
    printf '  removed skill %s\n' "$dest"
  else
    printf '  skill not installed (skipped): %s\n' "$dest"
  fi
}

print_next_steps() {
  ras_bin=$1
  ver=$2
  method=$3
  printf '\n'
  printf 'ras-anything %s is installed (%s).\n' "$ver" "$method"
  printf '  CLI:    %s\n' "$ras_bin"
  printf '  Skill:  %s/SKILL.md\n' "$CLAUDE_SKILL"
  printf '          %s/SKILL.md\n' "$CODEX_SKILL"
  printf '\n'
  printf 'Try it:\n'
  printf '  ras-anything --version\n'
  printf '  ras-anything doctor\n'
  printf '\n'
  printf 'MCP (stdio JSON-RPC) — add to your client, then start a new session:\n'
  printf '  claude mcp add ras-anything -- ras-anything mcp\n'
  printf '\n'
  printf '  Other MCP clients (Cursor, etc.), e.g. in .mcp.json or mcp.json:\n'
  printf '    {\n'
  printf '      "mcpServers": {\n'
  printf '        "ras-anything": { "command": "ras-anything", "args": ["mcp"] }\n'
  printf '      }\n'
  printf '    }\n'
  printf '\n'
  printf 'Claude Code plugin (from this clone; the GitHub repo is private — do not publish it):\n'
  printf '  /plugin marketplace add %s\n' "$ROOT"
  printf '  /plugin install ras-anything@ras-anything\n'
  printf '  /ras-anything:ras python app.py\n'
  printf '\n'
  printf 'Uninstall:\n'
  printf '  %s/install.sh --uninstall\n' "$ROOT"
  printf '  # or: make uninstall\n'
  case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
      printf '\n'
      printf 'Note: %s is not on PATH in this shell. Add this to your shell profile:\n' "$BIN_DIR"
      printf '  export PATH="%s:$PATH"\n' "$BIN_DIR"
      ;;
  esac
}

install_with_pipx() {
  # Isolated pipx locations so a custom HOME (or PIPX_* overrides) stays self-contained.
  if [ -z "${PIPX_HOME:-}" ]; then
    PIPX_HOME=$HOME/.local/pipx
    export PIPX_HOME
  fi
  if [ -z "${PIPX_BIN_DIR:-}" ]; then
    PIPX_BIN_DIR=$BIN_DIR
    export PIPX_BIN_DIR
  fi
  mkdir -p "$PIPX_BIN_DIR" "$PIPX_HOME"
  printf 'Installing CLI with pipx from %s ...\n' "$ROOT"
  pipx install --force "$ROOT"
  printf 'pipx\n' > "$MARKER"
  printf '%s\n' "$ROOT" >> "$MARKER"
}

install_with_venv() {
  if { [ -e "$SHIM" ] || [ -L "$SHIM" ]; } && ! is_our_shim "$SHIM" && [ "$FORCE" -ne 1 ]; then
    die "refusing to overwrite existing $SHIM (not an install.sh shim; remove it or re-run with --force)"
  fi
  py=$(check_python)
  printf 'pipx not found; installing CLI into %s (Python %s)\n' "$VENV_DIR" "$py"
  mkdir -p "$DATA_DIR" "$BIN_DIR"
  if [ ! -x "$VENV_DIR/bin/python" ]; then
    "$py" -m venv "$VENV_DIR" || die "failed to create venv at $VENV_DIR"
  fi
  "$VENV_DIR/bin/python" -m pip install --upgrade --disable-pip-version-check pip setuptools wheel
  "$VENV_DIR/bin/python" -m pip install --force-reinstall --disable-pip-version-check "$ROOT"
  # Invoke python -m ras_anything directly so paths with spaces work even if a pip script shebang wouldn't.
  printf '%s\n' "#!/bin/sh" "$SHIM_MARK" "exec \"${VENV_DIR}/bin/python\" -m ras_anything \"\$@\"" > "$SHIM"
  chmod +x "$SHIM"
  printf 'venv\n' > "$MARKER"
  printf '%s\n' "$ROOT" >> "$MARKER"
}

do_install() {
  [ -f "$ROOT/pyproject.toml" ] || die "run this script from a ras-anything checkout (missing pyproject.toml)"
  [ -f "$SKILL_SRC/SKILL.md" ] || die "missing $SKILL_SRC/SKILL.md"
  check_python >/dev/null
  mkdir -p "$DATA_DIR" "$BIN_DIR"

  if have pipx && pipx --version >/dev/null 2>&1; then
    install_with_pipx
    method=pipx
  else
    if have pipx; then
      printf 'pipx is on PATH but not runnable; falling back to a venv install.
'
    fi
    install_with_venv
    method=venv
  fi

  copy_skill "$SKILL_SRC" "$CLAUDE_SKILL"
  copy_skill "$SKILL_SRC" "$CODEX_SKILL"

  ras_bin=$SHIM
  if [ -x "$BIN_DIR/ras-anything" ]; then
    ras_bin=$BIN_DIR/ras-anything
  elif [ -x "$VENV_DIR/bin/ras-anything" ]; then
    ras_bin=$VENV_DIR/bin/ras-anything
  fi
  ver=$("$ras_bin" --version 2>/dev/null | awk '{print $NF}')
  ver=${ver:-unknown}
  printf 'Skills installed:\n  %s\n  %s\n' "$CLAUDE_SKILL/SKILL.md" "$CODEX_SKILL/SKILL.md"
  print_next_steps "$ras_bin" "$ver" "$method"
}

do_uninstall() {
  printf 'Uninstalling ras-anything (only files this installer wrote) ...\n'
  method=
  if [ -f "$MARKER" ]; then
    method=$(head -n 1 "$MARKER")
  fi

  if [ "$method" = "pipx" ] && have pipx; then
    if [ -z "${PIPX_HOME:-}" ]; then
      PIPX_HOME=$HOME/.local/pipx
      export PIPX_HOME
    fi
    if [ -z "${PIPX_BIN_DIR:-}" ]; then
      PIPX_BIN_DIR=$BIN_DIR
      export PIPX_BIN_DIR
    fi
    pipx uninstall ras-anything >/dev/null 2>&1 || true
    printf '  pipx package ras-anything removed (if it was installed)\n'
  fi

  if is_our_shim "$SHIM"; then
    rm -f "$SHIM"
    printf '  removed shim %s\n' "$SHIM"
  elif [ -e "$SHIM" ]; then
    printf '  left %s in place (not an install.sh shim)\n' "$SHIM"
  fi

  if [ -f "$MARKER" ] && [ -d "$VENV_DIR" ]; then
    rm -rf "$VENV_DIR"
    printf '  removed venv %s\n' "$VENV_DIR"
  fi

  remove_skill "$CLAUDE_SKILL"
  remove_skill "$CODEX_SKILL"

  rm -f "$MARKER"
  rmdir "$DATA_DIR" 2>/dev/null || true
  printf 'Uninstall complete.\n'
}

ACTION=install
while [ $# -gt 0 ]; do
  case "$1" in
    --install) ACTION=install ;;
    --uninstall) ACTION=uninstall ;;
    --force) FORCE=1 ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1 (try --help)" ;;
  esac
  shift
done

case "$ACTION" in
  install) do_install ;;
  uninstall) do_uninstall ;;
esac
