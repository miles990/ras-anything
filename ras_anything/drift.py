"""drift: model/prompt drift detection and promptfoo YAML export against recorded AI evals (V-14/V-15)."""

from __future__ import annotations

import json
import urllib.error
import urllib.request
from pathlib import Path

from . import ai, cassette, ui
from .paths import UserError, find_project, save_json, scrub


def _yaml_str(s: str) -> str:
    return json.dumps(str(s), ensure_ascii=False)


def save_eval_suite(project: Path, name: str, cases: list[dict]) -> Path:
    safe = "".join(c if c.isalnum() or c in ("-", "_", "@", ".") else "_" for c in name)
    p = project / ".ras" / "evals" / f"{safe}.json"
    save_json(p, scrub({"suite": name, "cases": cases}, project))
    return p


def _cases_from_cassettes(project: Path) -> list[dict]:
    base = project / ".ras" / "hardens"
    if not base.is_dir():
        return []
    cases: list[dict] = []
    for d in sorted(base.iterdir()):
        cp = d / "calls.json"
        if not cp.is_file():
            continue
        try:
            calls = cassette.load(cp)
        except Exception:
            continue
        for ci, c in enumerate(calls):
            for xi, x in enumerate(c.get("io") or []):
                req = x.get("req") or {}
                if not req.get("ai"):
                    continue
                out = x.get("out") or {}
                meta = ai.parse_response_meta(req.get("ai"), out.get("status", 200), out.get("body"))
                cases.append({
                    "id": f"{d.name}#c{ci}.io{xi}",
                    "model": meta["model"],
                    "url": req.get("url", ""),
                    "messages": [{"role": "user", "content": cassette.show(c.get("args"), 200)}],
                    "expected_schema": {"type": "object"},
                    "baseline_ok": out.get("status", 200) < 400 and "exc" not in out,
                    "baseline_tokens": meta["input_tokens"] + meta["output_tokens"],
                    "baseline_cost_usd": meta["cost_usd"],
                    "input_tokens": meta["input_tokens"],
                    "output_tokens": meta["output_tokens"],
                })
    return cases


def load_eval_suite(project: Path, eval_ref: str | None = None) -> tuple[str, list[dict]]:
    if eval_ref:
        cand = Path(eval_ref)
        if not cand.is_file():
            safe = "".join(c if c.isalnum() or c in ("-", "_", "@", ".") else "_" for c in eval_ref)
            cand = project / ".ras" / "evals" / (safe if safe.endswith(".json") else f"{safe}.json")
        if not cand.is_file():
            raise UserError("eval suite %r not found" % eval_ref,
                            "expected .ras/evals/<name>.json or a JSON file path",
                            "drift --model backup")
        data = json.loads(cand.read_text(encoding="utf-8"))
        cases = data.get("cases") if isinstance(data, dict) else data
        if not isinstance(cases, list) or not cases:
            raise UserError("eval suite %r has no cases" % eval_ref, "", "")
        return (data.get("suite") if isinstance(data, dict) else None) or cand.stem, cases
    cases = _cases_from_cassettes(project)
    if not cases:
        raise UserError("no AI eval suite or AI cassette found",
                        "record AI calls first with harden, or pass --eval <name>@v1",
                        "harden")
    return "cassettes", cases


def export_promptfoo(cases: list[dict], out_path: Path, models: list[str] | tuple[str, ...]) -> Path:
    """Write a promptfoo-compatible YAML config from recorded eval cases."""
    lines = [
        "# Generated by ras-anything drift --export-promptfoo",
        "description: ras-anything recorded AI drift suite",
        "prompts:",
        "  - {{prompt}}",
        "providers:",
    ]
    for m in models:
        lines.append(f"  - id: openai:chat:{m}")
    lines.append("tests:")
    for c in cases:
        prompt = ""
        msgs = c.get("messages") or []
        if msgs:
            prompt = str((msgs[-1] or {}).get("content") or c.get("id") or "")
        else:
            prompt = str(c.get("id") or "")
        lines.append("  - description: " + _yaml_str(c.get("id", "case")))
        lines.append("    vars:")
        lines.append("      prompt: " + _yaml_str(prompt))
        lines.append("    assert:")
        lines.append("      - type: is-json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def _eval_live(url: str, model: str, case: dict, config: dict) -> tuple[bool, int, float, str | None]:
    payload = {
        "model": model,
        "messages": case.get("messages") or [{"role": "user", "content": "ping"}],
        "max_tokens": case.get("max_tokens") or 128,
    }
    req = urllib.request.Request(
        url, data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"}, method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=5.0) as resp:
            raw = resp.read()
            status = resp.status
    except urllib.error.HTTPError as e:
        return False, 0, 0.0, f"HTTP {e.code}"
    except Exception as e:
        return False, 0, 0.0, str(e)
    meta = ai.parse_response_meta({"provider": "openai", "model": model, "input_tokens_est": 20}, status, raw, config)
    tokens = meta["input_tokens"] + meta["output_tokens"]
    try:
        doc = json.loads(raw.decode("utf-8"))
        content = (((doc.get("choices") or [{}])[0]).get("message") or {}).get("content")
        parsed = json.loads(content) if isinstance(content, str) else content
        req_keys = (case.get("expected_schema") or {}).get("required") or []
        ok = isinstance(parsed, dict) and all(k in parsed and bool(str(parsed[k]).strip()) for k in req_keys)
        return ok, tokens, meta["cost_usd"], None if ok else "schema_mismatch"
    except Exception as e:
        return False, tokens, meta["cost_usd"], f"bad_json: {e}"


def drift(model: str, eval_ref: str | None = None, provider_url: str | None = None,
          export_promptfoo_path: str | None = None, threshold: float = 0.05,
          quiet: bool = False, project: Path | None = None) -> dict:
    project = project or find_project()
    config = ai.load_ai_config(project)
    suite_name, cases = load_eval_suite(project, eval_ref)
    base_model = str(cases[0].get("model") or "small")
    if export_promptfoo_path:
        export_promptfoo(cases, Path(export_promptfoo_path), [base_model, model])

    base_ok = 0
    cand_ok = 0
    base_cost = 0.0
    cand_cost = 0.0
    details = []

    for c in cases:
        b_ok = bool(c.get("baseline_ok", True))
        in_tok = int(c.get("input_tokens") or 40)
        out_tok = int(c.get("output_tokens") or 20)
        raw_cost = c.get("baseline_cost_usd")
        b_cost = float(raw_cost) if raw_cost is not None else float(ai.estimate_cost(str(c.get("model") or base_model), in_tok, out_tok, config))
        base_ok += int(b_ok)
        base_cost += b_cost

        if provider_url:
            c_ok, _, c_cost, err = _eval_live(provider_url, model, c, config)
        else:
            # Deterministic offline projection using recorded baseline + model override / pricing table
            overrides = (c.get("model_outcomes") or {}).get(model)
            if isinstance(overrides, dict):
                c_ok = bool(overrides.get("ok", b_ok))
                c_in = int(overrides.get("input_tokens", in_tok))
                c_out = int(overrides.get("output_tokens", out_tok))
                c_cost = ai.estimate_cost(model, c_in, c_out, config)
                err = overrides.get("error")
            else:
                c_ok = b_ok
                c_cost = ai.estimate_cost(model, in_tok, out_tok, config)
                err = None if c_ok else "baseline_failed"
        cand_ok += int(c_ok)
        cand_cost += c_cost
        details.append({"id": c.get("id"), "baseline_ok": b_ok, "candidate_ok": c_ok, "error": err})

    n = len(cases)
    b_rate = round(base_ok / n, 4)
    c_rate = round(cand_ok / n, 4)
    delta = round(c_rate - b_rate, 4)
    cost_delta = round(cand_cost - base_cost, 6)
    passed = delta >= -abs(threshold)
    res = scrub({
        "suite": suite_name,
        "cases": n,
        "baseline_model": base_model,
        "candidate_model": model,
        "baseline_semantic_success": b_rate,
        "candidate_semantic_success": c_rate,
        "semantic_delta": delta,
        "baseline_cost_usd": round(base_cost, 6),
        "candidate_cost_usd": round(cand_cost, 6),
        "cost_delta_usd": cost_delta,
        "threshold": threshold,
        "passed": passed,
        "promptfoo_exported": export_promptfoo_path,
        "details": details,
    }, project)
    safe_suite = "".join(ch if ch.isalnum() or ch in ("-", "_") else "_" for ch in suite_name)
    safe_model = "".join(ch if ch.isalnum() or ch in ("-", "_") else "_" for ch in model)
    save_json(project / ".ras" / "drift" / f"{safe_suite}-{safe_model}.json", res)
    if not quiet:
        ui.headline("drift", f"{base_model} -> {model} ({n} cases, suite {suite_name})")
        print(f"  semantic success: {b_rate*100:.1f}% -> {c_rate*100:.1f}% (delta {delta*100:+.1f}%)")
        print(f"  estimated cost:   ${base_cost:.6f} -> ${cand_cost:.6f} (delta ${cost_delta:+.6f})")
        print(f"  verdict:          {'PASS' if passed else 'FAIL'}")
    return res
